/**
 * High-performance deterministic filter matching across verified real creators.
 */
export function queryVerifiedCreators(filters: CreatorSearchFilters): Creator[] {
  const queryFilter = (filters.query || "").trim().toLowerCase();
  const cityFilter = (filters.city || "").trim().toLowerCase();
  const stateFilter = (filters.state || "").trim().toLowerCase();
  const countryFilter = (filters.country || "").trim().toLowerCase();
  const genderFilter = filters.gender && (filters.gender as string) !== "all" ? filters.gender : null;
  const nichesFilter = (filters.niches || []).map((n) => n.toLowerCase());

  return VERIFIED_REAL_CREATORS.filter((creator) => {
    // City match
    if (cityFilter) {
      const c = (creator.cityNormalized || creator.city || "").toLowerCase();
      if (!c.includes(cityFilter) && !cityFilter.includes(c)) {
        return false;
      }
    }

    // State match
    if (stateFilter) {
      const s = (creator.stateNormalized || creator.state || "").toLowerCase();
      if (!s.includes(stateFilter) && !stateFilter.includes(s)) {
        return false;
      }
    }

    // Country match
    if (countryFilter && countryFilter !== "india") {
      const co = (creator.countryNormalized || creator.country || "").toLowerCase();
      if (!co.includes(countryFilter)) {
        return false;
      }
    }

    // Gender match
    if (genderFilter) {
      if (creator.creatorGender !== genderFilter && creator.creatorGender !== "unspecified") {
        return false;
      }
    }

    // Follower Range match
    if (filters.minFollowers !== null && creator.followersCount !== null) {
      if (creator.followersCount < filters.minFollowers) return false;
    }
    if (filters.maxFollowers !== null && creator.followersCount !== null) {
      if (creator.followersCount > filters.maxFollowers) return false;
    }

    // Engagement Rate match
    if (filters.minEngagementRate !== null && creator.engagementRate !== null) {
      if (creator.engagementRate < filters.minEngagementRate) return false;
    }

    // Niches match
    if (nichesFilter.length > 0) {
      const creatorNiches = (creator.niches || []).map((n) => n.toLowerCase());
      const primary = (creator.primaryNiche || "").toLowerCase();
      const hasNiche = nichesFilter.some((target) => {
        return (
          primary.includes(target) ||
          target.includes(primary) ||
          creatorNiches.some((cn) => cn.includes(target) || target.includes(cn))
        );
      });
      if (!hasNiche) return false;
    }

    // Keyword Search query
    if (queryFilter) {
      const matchName = (creator.displayName || "").toLowerCase().includes(queryFilter);
      const matchUsername = (creator.instagramUsername || "").toLowerCase().includes(queryFilter);
      const matchBio = (creator.bio || "").toLowerCase().includes(queryFilter);
      const matchNiche = (creator.primaryNiche || "").toLowerCase().includes(queryFilter);
      const matchCity = (creator.city || "").toLowerCase().includes(queryFilter);
      if (!matchName && !matchUsername && !matchBio && !matchNiche && !matchCity) {
        return false;
      }
    }

    return true;
  });
}
